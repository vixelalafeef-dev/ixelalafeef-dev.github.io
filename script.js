/* =========================================================
   INITIALIZATION
   ========================================================= */

document.addEventListener(
    "DOMContentLoaded",
    () => {

        /* Current year */

        const year =
            document.getElementById(
                "year"
            );

        if (year) {

            year.textContent =
                new Date()
                    .getFullYear();

        }


        /* Saved language */

        const savedLanguage =
            localStorage.getItem(
                "preferredLanguage"
            );


        if (
            savedLanguage &&
            translations[savedLanguage]
        ) {

            changeLanguage(
                savedLanguage
            );

        } else {

            changeLanguage("ar");

        }

    }
);
